/// Replaces the `meta` JSON for an existing auth session.
///
/// Updates the `meta` column of the row matching `session_id` with the supplied
/// JSON value. No error is returned if the session does not exist; the update
/// simply affects zero rows.
///
/// # Arguments
///
/// * `session_id` - The UUID of the session to update, as a string.
/// * `meta` - The JSON value to store in the `meta` column.
///
/// # Errors
///
/// Returns `sqlx::Error` if:
/// - The `session_id` is not a valid UUID
/// - The query fails
#[db_transaction(AuthPostGresDescriptor, UpdateAuthSessionMeta)]
async fn update_auth_session_meta(session_id: &str, meta: Value) -> () {
    let pool = T::yield_pool();
    let parsed_id: uuid::Uuid = session_id
        .parse()
        .map_err(|e| sqlx::Error::Protocol(format!("invalid session_id UUID: {}", e)))?;
    sqlx::query("UPDATE saps.auth_sessions SET meta = $1 WHERE id = $2")
        .bind(meta)
        .bind(parsed_id)
        .execute(pool)
        .await?;
    Ok(())
}

/// Sets a single key in the `meta` JSON of an existing auth session, leaving
/// all other keys intact, and returns the updated session.
///
/// If `meta` is `NULL`, it is treated as an empty object before the key is
/// inserted. If the key already exists, its value is overwritten; all other
/// keys are preserved. The merge happens server-side via `jsonb_set` so the
/// update is atomic with respect to concurrent writers. Returns
/// `Some(AuthSession<U>)` with the post-update row, or `None` if no session
/// exists for `session_id`.
///
/// # Arguments
///
/// * `session_id` - The UUID of the session to update, as a string.
/// * `key` - The top-level key to insert or overwrite in the `meta` object.
/// * `value` - The JSON value to associate with `key`.
///
/// # Errors
///
/// Returns `sqlx::Error` if:
/// - The `session_id` is not a valid UUID
/// - The query fails
/// - The returned `role` string cannot be parsed back into `U`
#[db_transaction(AuthPostGresDescriptor, UpsertAuthSessionMetaKey)]
async fn upsert_auth_session_meta_key<U: UserRole>(
    session_id: &str,
    key: &str,
    value: Value,
) -> Option<AuthSession<U>> {
    let pool = T::yield_pool();
    let parsed_id: uuid::Uuid = session_id
        .parse()
        .map_err(|e| sqlx::Error::Protocol(format!("invalid session_id UUID: {}", e)))?;
    let row = sqlx::query(
        "UPDATE saps.auth_sessions \
         SET meta = jsonb_set(COALESCE(meta, '{}'::jsonb), ARRAY[$1], $2, true) \
         WHERE id = $3 \
         RETURNING id, role, date_created, last_interacted, meta",
    )
        .bind(key)
        .bind(value)
        .bind(parsed_id)
        .fetch_optional(pool)
        .await?;
    match row {
        Some(r) => {
            let session =
                AuthSession::from_row(&r).map_err(|e| sqlx::Error::Protocol(e.message))?;
            Ok(Some(session))
        }
        None => Ok(None),
    }
}

/// Atomic compare-and-swap on a single top-level key in `meta`.
///
/// Updates `meta[key]` to `new_value` only if the current value at `key`
/// equals `expected`. The check and the write happen in a single
/// `UPDATE ... WHERE` so concurrent writers can't slip in between the read
/// and the write.
///
/// Returns `Some(AuthSession<U>)` with the post-update row when the swap
/// succeeded, or `None` when:
/// - The session does not exist,
/// - The key is absent from `meta` (or `meta` is `NULL`),
/// - The current value at `key` does not equal `expected`.
///
/// JSONB equality semantics apply: an explicit JSON `null` at `key` matches
/// an `expected` of `Value::Null`, but a missing key never matches anything
/// (because `meta -> 'missing'` is SQL `NULL` and `NULL = anything` is
/// unknown, so the row is filtered out).
///
/// # Arguments
///
/// * `session_id` - The UUID of the session to update, as a string.
/// * `key` - The top-level key in `meta` to compare and swap.
/// * `expected` - The JSON value that `meta[key]` must currently equal.
/// * `new_value` - The JSON value to write if the comparison matches.
///
/// # Errors
///
/// Returns `sqlx::Error` if:
/// - The `session_id` is not a valid UUID
/// - The query fails
/// - The returned `role` string cannot be parsed back into `U`
#[db_transaction(AuthPostGresDescriptor, CompareAndSwapAuthSessionMeta)]
async fn compare_and_swap_auth_session_meta<U: UserRole>(
    session_id: &str,
    key: &str,
    expected: Value,
    new_value: Value,
) -> Option<AuthSession<U>> {
    let pool = T::yield_pool();
    let parsed_id: uuid::Uuid = session_id
        .parse()
        .map_err(|e| sqlx::Error::Protocol(format!("invalid session_id UUID: {}", e)))?;
    let row = sqlx::query(
        "UPDATE saps.auth_sessions \
         SET meta = jsonb_set(meta, ARRAY[$2], $4, true) \
         WHERE id = $1 AND meta -> $2 = $3 \
         RETURNING id, role, date_created, last_interacted, meta",
    )
        .bind(parsed_id)
        .bind(key)
        .bind(expected)
        .bind(new_value)
        .fetch_optional(pool)
        .await?;
    match row {
        Some(r) => {
            let session =
                AuthSession::from_row(&r).map_err(|e| sqlx::Error::Protocol(e.message))?;
            Ok(Some(session))
        }
        None => Ok(None),
    }
}

/// Removes a single top-level key from the `meta` JSON of an existing auth
/// session, leaving all other keys intact, and returns the updated session.
///
/// Uses the PostgreSQL `jsonb - text` operator, which strips the named key
